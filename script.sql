declare
   procedure drop_table (
      p_table_name varchar2
   ) is
   begin
      execute immediate 'DROP TABLE "STUDIO"."'
                        || p_table_name
                        || '" CASCADE CONSTRAINTS';
   exception
      when others then
         if sqlcode != -942 then
            raise;
         end if;
   end;
begin
   drop_table('PAYMENT');
   drop_table('INVOICE');
   drop_table('LASER');
   drop_table('IMAGE_SESSION');
   drop_table('PRINT');
   drop_table('Order');
   drop_table('EMPLOYEE_SKILL');
   drop_table('EMPLOYEE_ROLE');
   drop_table('ATTENDANCE');
   drop_table('COUPON');
   drop_table('SKILL');
   drop_table('ROLE');
